import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { RadioStore } from '../src/store.js';
const project = mkdtempSync(join(tmpdir(), 'ai-radio-eval-'));
const store = new RadioStore(project);
for (const [name,provider] of [['codex','codex'],['claude','claude'],['reviewer','claude']]) store.register(name,provider);
const send = (sender,to,body,reply_to) => store.send(sender,{to,body,...(reply_to ? {reply_to} : {})});
const protocol = send('codex','claude','Parser proposal: wire version 3, maximum frame size 65536 bytes.');
const correction = send('claude','codex','Peer compatibility testing rejected that proposal. Use wire version 4 and maximum frame size 32768 bytes.',protocol.id);
send('codex','claude','Accepted both compatibility corrections; implement them.',correction.id);
const clock = send('claude','codex','Persisted times are shifted when daylight saving ends. Proposing a timezone migration.');
send('codex','claude','Store timestamps in UTC. America/Denver is for display only.',clock.id);
const retry = send('reviewer','codex','A retried delivery created a second job after a recipient change. Find the uniqueness bug.');
send('codex','reviewer','Confirmed: use sender plus retry_key as the unique pair, and reject changed recipients or content.',retry.id);
const rollout = send('codex','claude','Rollout plan: first canary on port 4100, then full deployment.');
const canary = send('claude','codex','Canary collided with an existing process. Reserve port 4200 instead. Release name is Vega.',rollout.id);
send('codex','claude','Accepted the port correction for Vega. Keep the previous rollback image.',canary.id);
send('reviewer','codex','Rollback image recorded as sha256:feedcafe. Frame tests passed the corrected cap.');
const offline = send('codex','claude','Operator recovery drill: process this later. Keep this message pending for the exercise.');
store.acknowledge('codex',[correction.id,canary.id]);
store.delivered([offline.id]);
store.close();
console.log(JSON.stringify({project,command:process.execPath,args:[resolve('bin/ai-radio.js'),'serve','--project',project,'--agent','codex','--provider','codex'],evaluation:resolve('eval/questions.xml'),note:'Fresh deterministic fixture. Connect read-only evaluation calls: radio_agents and radio_history. No model evaluation has been run by this script.'},null,2));
